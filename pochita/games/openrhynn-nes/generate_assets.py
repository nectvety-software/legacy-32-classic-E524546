def encode(rows):
    p0, p1 = [], []
    for row in rows:
        row = row.ljust(8, "0")[:8]
        a = b = 0
        for value in row:
            a = (a << 1) | (int(value) & 1)
            b = (b << 1) | ((int(value) >> 1) & 1)
        p0.append(a)
        p1.append(b)
    while len(p0) < 8:
        p0.append(0); p1.append(0)
    return bytes(p0 + p1)


def font_tile(ch):
    rows = FONT.get(ch, ["00000"] * 7)
    return encode(["0" + row + "00" for row in rows])


def four_tiles(canvas):
    out = []
    for oy, ox in ((0, 0), (0, 8), (8, 0), (8, 8)):
        out.append(encode([row[ox:ox + 8] for row in canvas[oy:oy + 8]]))
    return out


def actor(kind):
    c = [["0" for _ in range(16)] for _ in range(16)]
    def rect(x, y, w, h, color):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                if 0 <= xx < 16 and 0 <= yy < 16:
                    c[yy][xx] = str(color)
    if kind == "hero":
        rect(5, 1, 6, 5, 2); rect(4, 6, 8, 6, 1)
        rect(3, 8, 2, 5, 3); rect(11, 8, 2, 5, 3)
        rect(5, 12, 2, 4, 2); rect(9, 12, 2, 4, 2)
        rect(6, 3, 1, 1, 3); rect(9, 3, 1, 1, 3)
    elif kind == "elder":
        rect(5, 1, 6, 5, 3); rect(4, 6, 8, 8, 2)
        rect(6, 4, 4, 5, 1); rect(7, 3, 1, 1, 2); rect(9, 3, 1, 1, 2)
        rect(2, 9, 2, 7, 1); rect(12, 9, 2, 7, 1)
    elif kind == "wolf":
        rect(2, 6, 12, 7, 2); rect(10, 3, 4, 5, 2)
        rect(11, 2, 1, 2, 3); rect(14, 2, 1, 3, 3)
        rect(3, 13, 2, 3, 1); rect(10, 13, 2, 3, 1)
        rect(12, 5, 1, 1, 3)
    elif kind == "crystal":
        rect(7, 1, 2, 14, 1); rect(4, 5, 8, 6, 2); rect(6, 3, 4, 10, 3)
    return four_tiles(["".join(row) for row in c])


def build_chr():
    tiles = [bytes(16) for _ in range(512)]
    tiles[1] = encode(["00000000","00100000","00000000","00000100","00000000","01000000","00000010","00000000"])
    tiles[2] = encode(["00333000","03333300","33333330","33333330","03333300","00333000","00011000","00011000"])
    tiles[3] = encode(["11111111","12222221","12111121","12122121","12111121","12222221","11111111","11111111"])
    tiles[4] = encode(["11111111","22222222","11111111","22222222","11111111","22222222","11111111","22222222"])
    tiles[5] = encode(["00010000","00111000","00010000","00111000","00010000","00111000","00010000","00111000"])
    tiles[6] = encode(["00033000","00333300","03333330","33333333","33333333","33333333","33333333","33333333"])
    tiles[7] = encode(["22222222","21121112","22222222","11211211","22222222","21121112","22222222","11211211"])
    tiles[8] = encode(["11111111","12222221","12000021","12033021","12033021","12000021","12222221","11111111"])
    for code in range(32, 96):
        tiles[code] = font_tile(chr(code))
    sprite_index = 256
    for kind in ("hero", "elder", "wolf", "crystal"):
        for tile in actor(kind):
            tiles[sprite_index] = tile
            sprite_index += 1
    data = b"".join(tiles)
    assert len(data) == 8192
    (ROOT / "openrhynn.chr").write_bytes(data)


def build_nametable():
    nam = [32] * 960
    for y in range(4, 30):
        for x in range(32):
            nam[y * 32 + x] = 1
    for x in range(32):
        nam[4 * 32 + x] = 2
        nam[29 * 32 + x] = 2
    for y in range(4, 30):
        nam[y * 32] = 2
        nam[y * 32 + 31] = 2
    for y in range(7, 13):
        for x in range(3, 10):
            nam[y * 32 + x] = 6 if y < 9 else 7
    nam[12 * 32 + 6] = 8
    for x in range(6, 25):
        nam[14 * 32 + x] = 5
    for y in range(14, 25):
        nam[y * 32 + 17] = 5
    for y in range(18, 25):
        for x in range(22, 29):
            nam[y * 32 + x] = 4
    for x, y in ((13,7),(17,6),(23,8),(27,12),(4,18),(8,23),(13,26),(25,27)):
        nam[y * 32 + x] = 2
    attrs = [0] * 64
    for x in range(8):
        attrs[x] = 0x55
    data = bytes(nam + attrs)
    assert len(data) == 1024
    (ROOT / "openrhynn.nam").write_bytes(data)


